import { sql } from 'drizzle-orm';
import {
  boolean,
  customType,
  integer,
  pgEnum,
  pgTable,
  smallint,
  text,
  time,
  timestamp,
  uuid,
} from 'drizzle-orm/pg-core';

/**
 * Drizzle's view of the schema. The migrations in `migrations/` are the source
 * of truth (D-008); this file types the queries against them.
 */

const bytea = customType<{ data: Buffer; driverData: Buffer }>({
  dataType() {
    return 'bytea';
  },
});

export const appointmentStatus = pgEnum('appointment_status', ['CONFIRMED', 'CANCELLED']);
export const appointmentOrigin = pgEnum('appointment_origin', ['ONLINE', 'OWNER']);
export const appointmentActor = pgEnum('appointment_actor', ['CUSTOMER', 'OWNER']);

export const salon = pgTable('salon', {
  id: uuid('id').primaryKey(),
  name: text('name').notNull(),
  address: text('address').notNull(),
  phone: text('phone').notNull(),
  timezone: text('timezone').notNull(),
  /** Editable since 002 (D-022). 0–2880, in whole hours. */
  minimumLeadTimeMinutes: integer('minimum_lead_time_minutes').notNull().default(120),
  /** Editable since 002 (D-022). 0–72. */
  cancellationDeadlineHours: integer('cancellation_deadline_hours').notNull().default(24),
});

export const openingInterval = pgTable('opening_interval', {
  id: uuid('id').primaryKey(),
  weekday: smallint('weekday').notNull(),
  startsAt: time('starts_at').notNull(),
  endsAt: time('ends_at').notNull(),
});

/** Replaces the whole-day closure of 001 (002, D-019). Half-open `[starts_at, ends_at)`. */
export const unavailablePeriod = pgTable('unavailable_period', {
  id: uuid('id').primaryKey(),
  startsAt: timestamp('starts_at', { withTimezone: true, mode: 'date' }).notNull(),
  endsAt: timestamp('ends_at', { withTimezone: true, mode: 'date' }).notNull(),
  /** Internal. Never leaves the database: the client sees "closed", never why. */
  reason: text('reason'),
  createdAt: timestamp('created_at', { withTimezone: true, mode: 'date' })
    .notNull()
    .default(sql`now()`),
});

export const service = pgTable('service', {
  id: uuid('id').primaryKey(),
  name: text('name').notNull(),
  durationMinutes: integer('duration_minutes').notNull(),
  /** `NULL` is "no price" (FR-018), never 0. */
  priceCents: integer('price_cents'),
  isActive: boolean('is_active').notNull().default(true),
  displayOrder: integer('display_order').notNull(),
});

export const appointment = pgTable('appointment', {
  id: uuid('id').primaryKey(),
  status: appointmentStatus('status').notNull(),
  origin: appointmentOrigin('origin').notNull().default('ONLINE'),
  startsAt: timestamp('starts_at', { withTimezone: true, mode: 'date' }).notNull(),
  endsAt: timestamp('ends_at', { withTimezone: true, mode: 'date' }).notNull(),

  customerName: text('customer_name'),
  customerPhone: text('customer_phone'),
  customerEmail: text('customer_email'),
  customerPhoneNormalized: text('customer_phone_normalized'),
  customerEmailNormalized: text('customer_email_normalized'),
  /** Generated by 0006 from the name, as `searchableName` would (D-036). Never written. */
  customerNameSearch: text('customer_name_search').generatedAlwaysAs(
    sql`btrim(regexp_replace(lower(regexp_replace(normalize(customer_name, NFD), '[\u0300-\u036f]', '', 'g')), '\s+', ' ', 'g'))`,
  ),

  tokenHash: bytea('token_hash'),

  createdAt: timestamp('created_at', { withTimezone: true, mode: 'date' })
    .notNull()
    .default(sql`now()`),
  cancelledAt: timestamp('cancelled_at', { withTimezone: true, mode: 'date' }),
  cancelledBy: appointmentActor('cancelled_by'),
  anonymizedAt: timestamp('anonymized_at', { withTimezone: true, mode: 'date' }),
});

/** One row per service of an appointment, with its snapshot (005, D-001). */
export const appointmentService = pgTable('appointment_service', {
  appointmentId: uuid('appointment_id')
    .notNull()
    .references(() => appointment.id, { onDelete: 'cascade' }),
  position: smallint('position').notNull(),
  serviceId: uuid('service_id')
    .notNull()
    .references(() => service.id),
  name: text('name').notNull(),
  durationMinutes: integer('duration_minutes').notNull(),
  priceCents: integer('price_cents'),
});

/** The one staff account (002, FR-001). No column for an IP or a device (FR-009). */
export const ownerAccount = pgTable('owner_account', {
  id: uuid('id').primaryKey(),
  username: text('username').notNull(),
  /** `scrypt$N$r$p$salt$hash` (D-016). */
  passwordHash: text('password_hash').notNull(),
  passwordChangedAt: timestamp('password_changed_at', { withTimezone: true, mode: 'date' }).notNull(),
  failedAttempts: integer('failed_attempts').notNull().default(0),
  firstFailedAttemptAt: timestamp('first_failed_attempt_at', { withTimezone: true, mode: 'date' }),
  lockedUntil: timestamp('locked_until', { withTimezone: true, mode: 'date' }),
  createdAt: timestamp('created_at', { withTimezone: true, mode: 'date' })
    .notNull()
    .default(sql`now()`),
});

/** One live session per row; only the token's SHA-256 is kept (D-015). */
export const ownerSession = pgTable('owner_session', {
  id: uuid('id').primaryKey(),
  accountId: uuid('account_id')
    .notNull()
    .references(() => ownerAccount.id, { onDelete: 'cascade' }),
  tokenHash: bytea('token_hash').notNull(),
  createdAt: timestamp('created_at', { withTimezone: true, mode: 'date' }).notNull(),
  lastSeenAt: timestamp('last_seen_at', { withTimezone: true, mode: 'date' }).notNull(),
});

export const schema = {
  salon,
  openingInterval,
  unavailablePeriod,
  service,
  appointment,
  appointmentService,
  ownerAccount,
  ownerSession,
};
